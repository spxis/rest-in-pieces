/** Documentation for the public types written by openapi-typescript; schemas and declarations remain its output. */
const EXAMPLES: Record<string, { summary: string; code: string }> = {
  paths: {
    summary:
      'Every HTTP path, method, parameter and response in the generated OpenAPI document. Index by a path and method to type a client request or response without starting a server.',
    code: 'import type { paths } from "@johnmorrisdotca/rest-in-pieces/types";\n\nconst route: keyof paths = "/users";\nconsole.log(route);',
  },
  webhooks: {
    summary:
      'The generated webhook map. This API declares no outgoing webhook operations, so the map is empty rather than a catalogue of available hooks.',
    code: 'import type { webhooks } from "@johnmorrisdotca/rest-in-pieces/types";\n\nconst hooks: webhooks = {};\nconsole.log(Object.keys(hooks).length);',
  },
  components: {
    summary:
      'The generated reusable OpenAPI schemas, parameters and responses. Index schemas by their documented name to type a returned record; the records themselves are still generated by the API.',
    code: 'import type { components } from "@johnmorrisdotca/rest-in-pieces/types";\n\ntype Person = components["schemas"]["Person"];\nconst name: Person["name"] = "Ada Lovelace";\nconsole.log(name);',
  },
  $defs: {
    summary:
      'The generated top-level JSON Schema definitions map. No top-level definitions are declared; reusable API record schemas live in components.schemas.',
    code: 'import type { $defs } from "@johnmorrisdotca/rest-in-pieces/types";\n\nconst definitions: $defs = {};\nconsole.log(Object.keys(definitions).length);',
  },
  operations: {
    summary:
      'Every named operation in the generated OpenAPI document, with its request and response types. Use an operation identifier to type its query or response independently of the URL.',
    code: 'import type { operations } from "@johnmorrisdotca/rest-in-pieces/types";\n\nconst query: operations["validate_address"]["parameters"]["query"] = {\n  address: "111 King St W Toronto ON M5H 1J9",\n  country: "CA",\n};\nconsole.log(query.country);',
  },
};

/** Adds comments to public generated declarations, failing if a new export needs documentation. */
export function documentOpenApiTypes(types: string): string {
  const seen = new Set<string>();
  const result = types.replace(/^(export (?:interface|type) ([\w$]+)\b)/gm, (declaration, _whole, name: string) => {
    const example = EXAMPLES[name];
    if (!example) throw new Error(`Public OpenAPI type ${name} needs a documented example in scripts/docs-openapi.ts`);
    seen.add(name);
    const text = `${example.summary}\n\n@example\n\`\`\`ts\n${example.code}\n\`\`\``;
    return `/**\n${text
      .split('\n')
      .map((line) => ` *${line ? ` ${line}` : ''}`)
      .join('\n')}\n */\n${declaration}`;
  });
  for (const name of Object.keys(EXAMPLES)) {
    if (!seen.has(name))
      throw new Error(`The generated OpenAPI declarations no longer export ${name}; update its documentation`);
  }
  return result;
}
