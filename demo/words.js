/** Fills {name} gaps in a sentence. */
export const fill = (text, values = {}) =>
  text.replace(/\{(\w+)\}/g, (_, key) =>
    values[key] === undefined ? `{${key}}` : Number(values[key]).toLocaleString('en-US'),
  );
